import React, { useState } from 'react';
import { motion, AnimatePresence } from 'framer-motion';
import { BotanicalDivider } from './BotanicalDecorations';
import { SacredLotusMotif } from './TraditionalMotifs';
import { createClient } from '@supabase/supabase-js';
import { CheckCircle2, AlertCircle, HeartHandshake, Sparkles, Send, Database, Info, Copy, Check } from 'lucide-react';
import confetti from 'canvas-confetti';

export const RSVPForm = ({ lang, t, config }) => {
  const [formData, setFormData] = useState({
    guestName: '',
    phone: '',
    guestCount: 2,
    attendance: 'accept', // 'accept' or 'decline'
    dietary: 'Traditional South Indian Vegetarian',
    message: '',
  });

  const [isSubmitting, setIsSubmitting] = useState(false);
  const [isSubmitted, setIsSubmitted] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');
  const [storageStatus, setStorageStatus] = useState(null); // 'supabase' | 'local'
  const [showSetupGuide, setShowSetupGuide] = useState(false);
  const [copiedSql, setCopiedSql] = useState(false);

  // Check if real Supabase backend is configured
  const hasSupabase = Boolean(config.supabase?.url && config.supabase?.anonKey);

  const sqlSchema = `CREATE TABLE wedding_rsvps (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  guest_name TEXT NOT NULL,
  phone TEXT NOT NULL,
  guest_count INTEGER DEFAULT 1,
  attendance TEXT NOT NULL,
  dietary TEXT,
  message TEXT,
  language TEXT DEFAULT 'en'
);`;

  const copySqlToClipboard = () => {
    navigator.clipboard.writeText(sqlSchema);
    setCopiedSql(true);
    setTimeout(() => setCopiedSql(false), 3000);
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setErrorMsg('');

    // Validation
    if (!formData.guestName.trim()) {
      setErrorMsg(lang === 'kn' ? 'ದಯವಿಟ್ಟು ನಿಮ್ಮ ಹೆಸರನ್ನು ನಮೂದಿಸಿ.' : 'Please enter your full name.');
      return;
    }
    if (!formData.phone.trim() || formData.phone.length < 8) {
      setErrorMsg(lang === 'kn' ? 'ದಯವಿಟ್ಟು ಮಾನ್ಯವಾದ ಮೊಬೈಲ್ ಸಂಖ್ಯೆಯನ್ನು ನಮೂದಿಸಿ.' : 'Please enter a valid phone number.');
      return;
    }

    setIsSubmitting(true);

    const payload = {
      guest_name: formData.guestName.trim(),
      phone: formData.phone.trim(),
      guest_count: Number(formData.guestCount),
      attendance: formData.attendance,
      dietary: formData.dietary,
      message: formData.message.trim(),
      language: lang,
    };

    try {
      if (hasSupabase) {
        // Genuine Supabase save
        const supabase = createClient(config.supabase.url, config.supabase.anonKey);
        const { error } = await supabase
          .from(config.supabase.tableName || 'wedding_rsvps')
          .insert([payload]);

        if (error) {
          throw new Error(error.message);
        }
        setStorageStatus('supabase');
      } else {
        // Genuine local storage fallback with clear notification
        const existingRsvps = JSON.parse(localStorage.getItem('wedding_rsvps') || '[]');
        existingRsvps.push({
          ...payload,
          id: Date.now(),
          created_at: new Date().toISOString(),
        });
        localStorage.setItem('wedding_rsvps', JSON.stringify(existingRsvps));
        setStorageStatus('local');
      }

      // Celebrate with dried floral / terracotta confetti
      if (formData.attendance === 'accept') {
        try {
          confetti({
            particleCount: 50,
            spread: 80,
            origin: { y: 0.6 },
            colors: ['#986B58', '#C5A58F', '#C5A059'],
          });
        } catch (e) {}
      }

      setIsSubmitted(true);
    } catch (err) {
      console.error('RSVP Submission error:', err);
      setErrorMsg(err.message || 'Failed to submit RSVP. Please try again.');
    } finally {
      setIsSubmitting(false);
    }
  };

  const handleReset = () => {
    setIsSubmitted(false);
    setFormData({
      guestName: '',
      phone: '',
      guestCount: 2,
      attendance: 'accept',
      dietary: 'Traditional South Indian Vegetarian',
      message: '',
    });
  };

  return (
    <section id="rsvp" className="py-16 sm:py-24 relative overflow-hidden">
      <div className="max-w-3xl mx-auto px-4 sm:px-6 relative z-10">
        
        {/* Header */}
        <div className="text-center max-w-xl mx-auto mb-10 sm:mb-14">
          <div className="inline-flex items-center gap-1.5 px-4 py-1.5 rounded-full bg-[#FAF6F0]/80 backdrop-blur-md border border-[#C5A58F]/40 text-[#795345] text-xs font-cinzel tracking-[0.2em] uppercase mb-2.5 shadow-2xs font-medium">
            <HeartHandshake className="w-3.5 h-3.5 text-[#986B58]" />
            <span>{t.rsvp.badge}</span>
          </div>
          <h2 className="text-3xl sm:text-5xl font-serif text-[#442E25] tracking-tight font-normal">
            {t.rsvp.heading}
          </h2>
          <p className="text-xs sm:text-sm font-serif italic text-[#795345] mt-2">
            {t.rsvp.subtitle}
          </p>
          <BotanicalDivider className="my-5" />
        </div>

        {/* Backend Status Notice */}
        <div className="mb-6 p-3.5 rounded-2xl glass-stationery-card flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 text-xs text-[#442E25] shadow-2xs">
          <div className="flex items-center gap-2">
            <Database className="w-4 h-4 text-[#986B58] shrink-0" />
            <span>
              {hasSupabase ? (
                <strong className="text-emerald-900 font-semibold">
                  {lang === 'kn' ? 'ಸುಪಾಬೇಸ್ (Supabase) ಕನೆಕ್ಟ್ ಆಗಿದೆ' : 'Connected to Supabase Database'}
                </strong>
              ) : (
                <span className="font-medium text-[#795345]">
                  {lang === 'kn'
                    ? 'ಡೆಮೊ ಮೋಡ್ (ಬ್ರೌಸರ್‌ನಲ್ಲಿ ಸುರಕ್ಷಿತವಾಗಿ ಸೇವ್ ಆಗುತ್ತದೆ)'
                    : 'Demo Mode: Storing locally in browser (Supabase keys not set in config)'}
                </span>
              )}
            </span>
          </div>

          <button
            type="button"
            onClick={() => setShowSetupGuide(!showSetupGuide)}
            className="text-[11px] font-sans font-medium text-[#986B58] hover:text-[#795345] underline flex items-center gap-1 shrink-0"
          >
            <Info className="w-3.5 h-3.5" />
            <span>{showSetupGuide ? (lang === 'kn' ? 'ಮರೆಮಾಚಿ' : 'Hide Guide') : (lang === 'kn' ? 'ಸುಪಾಬೇಸ್ ಸೆಟಪ್ ವಿವರ' : 'Supabase Setup Guide')}</span>
          </button>
        </div>

        {/* Collapsible Supabase Instructions */}
        {showSetupGuide && (
          <div className="mb-8 p-5 rounded-2xl bg-[#FAF6F0]/95 backdrop-blur-xl border border-[#C5A58F]/40 text-xs text-[#442E25] shadow-lg">
            <h4 className="font-serif font-semibold text-sm text-[#986B58] mb-2">
              Supabase Backend Setup Instructions
            </h4>
            <ol className="list-decimal pl-4 space-y-1.5 text-xs text-[#795345] mb-3 font-medium">
              <li>Create a free project at <strong>supabase.com</strong>.</li>
              <li>Open SQL Editor and execute the schema below to create the table.</li>
              <li>Add your Project URL and anon key to <code>src/config/weddingDetails.js</code> (or create a <code>.env</code> file with <code>VITE_SUPABASE_URL</code> and <code>VITE_SUPABASE_ANON_KEY</code>).</li>
            </ol>
            <div className="relative">
              <pre className="p-3 rounded-lg bg-[#2D211A] text-[#F7F2EC] font-mono text-[11px] overflow-x-auto">
                {sqlSchema}
              </pre>
              <button
                type="button"
                onClick={copySqlToClipboard}
                className="absolute top-2 right-2 px-2.5 py-1 rounded bg-[#986B58] hover:bg-[#795345] text-white text-[10px] font-sans flex items-center gap-1"
              >
                {copiedSql ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>{copiedSql ? 'Copied' : 'Copy SQL'}</span>
              </button>
            </div>
          </div>
        )}

        {/* Translucent Stationery Form Container */}
        <div className="glass-stationery rounded-3xl p-6 sm:p-10 md:p-12">
          <AnimatePresence mode="wait">
            {isSubmitted ? (
              /* Success Screen */
              <motion.div
                key="success"
                initial={{ opacity: 0, scale: 0.95 }}
                animate={{ opacity: 1, scale: 1 }}
                exit={{ opacity: 0 }}
                className="text-center py-6"
              >
                <div className="w-16 h-16 rounded-full bg-emerald-100/90 text-emerald-800 flex items-center justify-center mx-auto mb-4 border border-emerald-300 shadow-xs">
                  <CheckCircle2 className="w-8 h-8" />
                </div>
                <h3 className="text-2xl sm:text-3xl font-serif text-[#442E25] font-normal mb-2">
                  {t.rsvp.successTitle}
                </h3>
                <p className="text-xs sm:text-sm font-serif italic text-[#795345] max-w-md mx-auto mb-6">
                  {t.rsvp.successDesc}
                </p>

                <p className="text-[11px] font-sans text-[#986B58] font-medium bg-white/70 backdrop-blur-md p-3 rounded-xl border border-[#C5A58F]/30 max-w-sm mx-auto mb-6 shadow-2xs">
                  {storageStatus === 'supabase' ? t.rsvp.backendNotice : t.rsvp.backendLocalNotice}
                </p>

                <button
                  onClick={handleReset}
                  className="px-6 py-2.5 rounded-full border border-[#C5A58F]/40 bg-white/80 hover:bg-[#FAF6F0] text-xs font-cinzel uppercase tracking-wider text-[#442E25] font-medium transition-all shadow-2xs"
                >
                  {t.rsvp.sendAnother}
                </button>
              </motion.div>
            ) : (
              /* RSVP Form */
              <motion.form
                key="form"
                initial={{ opacity: 0 }}
                animate={{ opacity: 1 }}
                exit={{ opacity: 0 }}
                onSubmit={handleSubmit}
                className="space-y-6"
              >
                {errorMsg && (
                  <div className="p-3.5 rounded-xl bg-red-50/90 backdrop-blur-md border border-red-200 text-red-900 text-xs flex items-center gap-2 font-medium">
                    <AlertCircle className="w-4 h-4 shrink-0 text-red-700" />
                    <span>{errorMsg}</span>
                  </div>
                )}

                {/* Guest Name & Mobile Number */}
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-5">
                  <div>
                    <label className="block text-[11px] font-cinzel uppercase tracking-[0.18em] text-[#795345] mb-2 font-medium">
                      {t.rsvp.nameLabel}
                    </label>
                    <input
                      type="text"
                      required
                      value={formData.guestName}
                      onChange={(e) => setFormData({ ...formData, guestName: e.target.value })}
                      placeholder={t.rsvp.namePlaceholder}
                      className="w-full px-4 py-3 rounded-xl bg-white/80 backdrop-blur-md border border-[#C5A58F]/40 text-[#442E25] text-sm focus:bg-white focus:border-[#986B58] focus:ring-1 focus:ring-[#986B58] outline-none transition-all placeholder:text-[#795345]/50 font-sans"
                    />
                  </div>

                  <div>
                    <label className="block text-[11px] font-cinzel uppercase tracking-[0.18em] text-[#795345] mb-2 font-medium">
                      {t.rsvp.phoneLabel}
                    </label>
                    <input
                      type="tel"
                      required
                      value={formData.phone}
                      onChange={(e) => setFormData({ ...formData, phone: e.target.value })}
                      placeholder={t.rsvp.phonePlaceholder}
                      className="w-full px-4 py-3 rounded-xl bg-white/80 backdrop-blur-md border border-[#C5A58F]/40 text-[#442E25] text-sm focus:bg-white focus:border-[#986B58] focus:ring-1 focus:ring-[#986B58] outline-none transition-all placeholder:text-[#795345]/50 font-sans"
                    />
                  </div>
                </div>

                {/* Number of Guests & Dietary Preference */}
                <div className="grid grid-cols-1 sm:grid-cols-2 gap-5">
                  <div>
                    <label className="block text-[11px] font-cinzel uppercase tracking-[0.18em] text-[#795345] mb-2 font-medium">
                      {t.rsvp.guestsLabel}
                    </label>
                    <select
                      value={formData.guestCount}
                      onChange={(e) => setFormData({ ...formData, guestCount: Number(e.target.value) })}
                      className="w-full px-4 py-3 rounded-xl bg-white/80 backdrop-blur-md border border-[#C5A58F]/40 text-[#442E25] text-sm focus:bg-white focus:border-[#986B58] focus:ring-1 focus:ring-[#986B58] outline-none transition-all font-sans"
                    >
                      {[1, 2, 3, 4, 5, 6, 8, 10].map((num) => (
                        <option key={num} value={num}>
                          {num} {num === 1 ? (lang === 'kn' ? 'ವ್ಯಕ್ತಿ' : 'Guest') : (lang === 'kn' ? 'ವ್ಯಕ್ತಿಗಳು' : 'Guests')}
                        </option>
                      ))}
                    </select>
                  </div>

                  <div>
                    <label className="block text-[11px] font-cinzel uppercase tracking-[0.18em] text-[#795345] mb-2 font-medium">
                      {t.rsvp.dietaryLabel}
                    </label>
                    <select
                      value={formData.dietary}
                      onChange={(e) => setFormData({ ...formData, dietary: e.target.value })}
                      className="w-full px-4 py-3 rounded-xl bg-white/80 backdrop-blur-md border border-[#C5A58F]/40 text-[#442E25] text-sm focus:bg-white focus:border-[#986B58] focus:ring-1 focus:ring-[#986B58] outline-none transition-all font-sans"
                    >
                      <option value="Traditional South Indian Vegetarian">{t.rsvp.dietaryTraditional}</option>
                      <option value="Jain Vegetarian">{t.rsvp.dietaryJain}</option>
                      <option value="General Vegetarian Feast">{t.rsvp.dietaryGeneral}</option>
                    </select>
                  </div>
                </div>

                {/* Attendance Options */}
                <div>
                  <label className="block text-[11px] font-cinzel uppercase tracking-[0.18em] text-[#795345] mb-2.5 font-medium">
                    {t.rsvp.attendanceLabel}
                  </label>
                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
                    <label
                      className={`p-4 rounded-xl border cursor-pointer flex items-center gap-3 transition-all ${
                        formData.attendance === 'accept'
                          ? 'border-[#986B58]/60 bg-white/95 shadow-xs'
                          : 'border-[#C5A58F]/30 bg-white/60 hover:bg-white/80'
                      }`}
                    >
                      <input
                        type="radio"
                        name="attendance"
                        value="accept"
                        checked={formData.attendance === 'accept'}
                        onChange={() => setFormData({ ...formData, attendance: 'accept' })}
                        className="accent-[#986B58] w-4 h-4"
                      />
                      <span className="text-xs sm:text-sm font-serif font-medium text-[#442E25]">
                        {t.rsvp.acceptOption}
                      </span>
                    </label>

                    <label
                      className={`p-4 rounded-xl border cursor-pointer flex items-center gap-3 transition-all ${
                        formData.attendance === 'decline'
                          ? 'border-[#986B58]/60 bg-white/95 shadow-xs'
                          : 'border-[#C5A58F]/30 bg-white/60 hover:bg-white/80'
                      }`}
                    >
                      <input
                        type="radio"
                        name="attendance"
                        value="decline"
                        checked={formData.attendance === 'decline'}
                        onChange={() => setFormData({ ...formData, attendance: 'decline' })}
                        className="accent-[#986B58] w-4 h-4"
                      />
                      <span className="text-xs sm:text-sm font-serif font-medium text-[#795345]">
                        {t.rsvp.declineOption}
                      </span>
                    </label>
                  </div>
                </div>

                {/* Optional Message / Blessings */}
                <div>
                  <label className="block text-[11px] font-cinzel uppercase tracking-[0.18em] text-[#795345] mb-2 font-medium">
                    {t.rsvp.messageLabel}
                  </label>
                  <textarea
                    rows={3}
                    value={formData.message}
                    onChange={(e) => setFormData({ ...formData, message: e.target.value })}
                    placeholder={t.rsvp.messagePlaceholder}
                    className="w-full px-4 py-3 rounded-xl bg-white/80 backdrop-blur-md border border-[#C5A58F]/40 text-[#442E25] text-sm focus:bg-white focus:border-[#986B58] focus:ring-1 focus:ring-[#986B58] outline-none transition-all placeholder:text-[#795345]/50 font-sans"
                  />
                </div>

                {/* Submit Button */}
                <div className="pt-2 text-center">
                  <button
                    type="submit"
                    disabled={isSubmitting}
                    className="w-full sm:w-auto min-w-[250px] px-8 py-3.5 rounded-full bg-[#986B58] hover:bg-[#795345] text-[#FAF6F0] text-xs sm:text-sm font-cinzel font-medium tracking-[0.2em] uppercase shadow-md hover:shadow-lg transition-all flex items-center justify-center gap-2 mx-auto disabled:opacity-60 border border-[#C5A58F]/40"
                  >
                    {isSubmitting ? (
                      <span>{t.rsvp.submitting}</span>
                    ) : (
                      <>
                        <Send className="w-4 h-4 text-[#E9DDD1]" />
                        <span>{t.rsvp.submitButton}</span>
                        <Sparkles className="w-3.5 h-3.5 text-[#C5A059]" />
                      </>
                    )}
                  </button>
                </div>
              </motion.form>
            )}
          </AnimatePresence>
        </div>

      </div>
    </section>
  );
};

export default RSVPForm;
